function normalizarTexto(texto) {
  return texto
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
}

export function buscarCidade(nome) {
  const termo = normalizarTexto(nome)
  if (!termo) return null
  return dadosClima.find(item => normalizarTexto(item.name).includes(termo))
}

